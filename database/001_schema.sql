-- PostgreSQL exécute les fichiers *.sql de ce dossier uniquement à
-- l'initialisation d'un nouveau volume. Pour une base déjà initialisée,
-- appliquer les changements explicitement (voir README.md).
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL,
    password text NOT NULL, -- Hash du mot de passe uniquement.
    email text NOT NULL,
    activation boolean NOT NULL FALSE,
    activation_token_hash TEXT,
    activation_token_expires_at TIMESTAMPTZ
);

-- L'unicité porte sur chaque champ séparément, sans distinction de casse.
CREATE UNIQUE INDEX users_login_unique ON users (lower(btrim(login)));
CREATE UNIQUE INDEX users_email_unique ON users (lower(btrim(email)));
