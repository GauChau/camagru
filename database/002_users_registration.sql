-- Adapter la table users initiale sans supprimer les enregistrements existants.
-- Sur un nouveau volume, 001_schema.sql a déjà créé ces protections.
BEGIN;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
          AND column_name = 'id' AND is_identity = 'NO'
    ) THEN
        ALTER TABLE users ALTER COLUMN id SET NOT NULL;
        ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.users'::regclass AND contype = 'p'
    ) THEN
        ALTER TABLE users ADD PRIMARY KEY (id);
    END IF;
END $$;

-- Le prochain identifiant doit venir après les identifiants déjà présents.
SELECT setval(
    pg_get_serial_sequence('users', 'id'),
    greatest(coalesce((SELECT max(id) FROM users), 0) + 1, 1),
    false
);

CREATE UNIQUE INDEX IF NOT EXISTS users_login_unique ON users (lower(btrim(login)));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON users (lower(btrim(email)));

COMMIT;
